/**
 * コラム記事：リハビリ計画の説明、医師以外でもよい場合と報告の手順
 *
 * ★核になる事実は一次資料で直接確認したもの（2026-08-12）。
 * 厚生労働大臣が定める基準（平成27年厚生労働省告示第95号）現行溶け込み版
 * 「二十五 通所リハビリテーション費におけるリハビリテーションマネジメント加算の基準」
 * イ(2)：計画の作成に関与した医師・PT・OT・STが説明し同意を得る。ただしPT・OT・STが
 * 説明した場合は説明した内容等について医師へ報告する。
 * https://www.mhlw.go.jp/web/t_doc?dataId=82ab4584&dataType=0&pageNo=1
 *
 * 医師が説明した場合の上乗せ（270単位/月）は `tsusho-riha-rehamane` の units に、
 * 訪問リハの同構造は `homon-riha-rehamane` の units にある（いずれも genpon）。
 *
 * ★この記事は通所リハの基準に限定して書く。サービスごとに基準が別なので、
 * 「リハ計画一般のルール」として広げないこと。
 */

